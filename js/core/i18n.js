module.exports = {
  lang: function () {
    var l = Save.get('lang');
    return l === 'en' ? 'en' : 'zh';
  },
  /** 取词条：{n}/{name} 占位符用 args 对象替换 */
  t: function (key, args) {
    var d = DICT[this.lang()] || DICT.zh;
    var s = d[key] !== undefined ? d[key] : (DICT.zh[key] !== undefined ? DICT.zh[key] : key);
    if (args) {
      for (var k in args) s = s.split('{' + k + '}').join(args[k]);
    }
    return s;
  }
};
